#!/usr/bin/env node
/** Writes frontend/src/app/core/build-info.ts with git short SHA (dev smoke). */
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'frontend/src/app/core/build-info.ts');

let sha = 'unknown';
try {
  sha = execSync('git rev-parse --short HEAD', { cwd: root, encoding: 'utf8' }).trim();
} catch {
  /* not a git repo or git missing */
}

const generatedAt = new Date().toISOString();
const content = `/** Auto-generated by scripts/write-build-info.mjs — do not edit manually */
export const BUILD_INFO: { readonly sha: string; readonly generatedAt: string } = {
  sha: '${sha}',
  generatedAt: '${generatedAt}',
};
`;

writeFileSync(out, content, 'utf8');
console.log(`[build-info] ${sha} → frontend/src/app/core/build-info.ts`);
